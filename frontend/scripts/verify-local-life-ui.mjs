  await receipt.getByText("餐饮请求超过当前单笔上限。").waitFor();
  await page.getByRole("button",{name:"确认本次例外并执行"}).waitFor();
  await page.getByRole("button",{name:"确认本次例外并执行"}).click();
  await receipt.getByText("Tool Receipt / Result · dining-confirm").waitFor();
  await page.getByText("餐饮 · ¥680").waitFor({state:"hidden"});
  await page.reload({waitUntil:"domcontentloaded"});
  await page.waitForFunction(()=>Number(document.querySelector('[data-testid="twin-sync"]')?.getAttribute("data-twin-version"))>=5);
