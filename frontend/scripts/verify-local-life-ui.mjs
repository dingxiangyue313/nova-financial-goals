  await page.goto(process.env.NOVA_BASE_URL??"http://localhost:5173/",{waitUntil:"domcontentloaded"});
  await page.waitForFunction(()=>Number(document.querySelector('[data-testid="twin-sync"]')?.getAttribute("data-twin-version"))>0);
  await page.getByRole("button",{name:"Life",exact:true}).click();
  const receipt=page.locator(".life-result");
  await page.getByRole("button",{name:"执行",exact:true}).click();
  await receipt.getByText("请先创建有效的 30 天生活授权。").waitFor();
  await page.getByRole("button",{name:"创建 30 天生活授权"}).click();
  await receipt.getByText("Tool Receipt / Result · mandate-create").waitFor();
  await page.getByRole("button",{name:"执行",exact:true}).click();
  await receipt.getByText("Tool Receipt / Result · transport").waitFor();
  await page.getByText("交通 · ¥18").waitFor({state:"hidden"});
  await page.getByRole("button",{name:"确认",exact:true}).click();
  await receipt.getByText("Tool Receipt / Result · shopping").waitFor();
  await page.getByText("购物 · ¥280").waitFor({state:"hidden"});
  await page.getByRole("button",{name:"生成转账草案并检查风险"}).click();
  await receipt.getByText("Tool Receipt / Result · prepare-transfer").waitFor();
